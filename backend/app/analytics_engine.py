                f"Аргумент аналитика: ключевой фактор — стабильность вратаря и агрессивная силовая борьба в чужой зоне. В 4 из 5 последних очных встреч перевес был на стороне фаворита, поэтому выбор «{outcome}» с кэфом {odds} выглядит максимально надежно.",
                f"Мнение капперов: игровая дисциплина и надежность при игре в обороне позволяют контролировать среднюю зону. Соперник испытывает кадровые проблемы во второй паре защитников."
