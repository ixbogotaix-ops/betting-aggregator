def generate_cappers_consensus_reasoning(
    supporting_sources: List[str],
    outcome: str,
    odds: float
) -> str:
    """
    Сводная мысль всех капперов.
    """
    count = len(supporting_sources) if supporting_sources else 1
    return (
        f"Аналитическое ядро зафиксировало единогласный консенсус {count} независимых источников в пользу исхода «{outcome}» с коэффициентом {odds:.2f}. "
        f"Эксперты спортивных порталов и профильные Telegram-капперы единодушны: текущий игровой тонус, отсутствие критических кадровых потерь "
        f"и тактическое соответствие стилей соперников делают данную ставку приоритетной на сегодняшний день."
    )
